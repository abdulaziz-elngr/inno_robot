import {
  boolean,
  index,
  integer,
  jsonb,
  pgTable,
  text,
  timestamp,
  uniqueIndex,
} from "drizzle-orm/pg-core";
import type {
  COMMAND_STATUSES,
  COMMAND_TYPES,
  DEVICE_MODES,
  DEVICE_STATUSES} from "./common";
import {
  createdAtCol,
  idCol,
  updatedAtCol,
} from "./common";
import { users } from "./auth";
import { campusLocations, navigationDestinations } from "./campus";

/** Public device registry. Contains no secrets. */
export const robotDevices = pgTable(
  "robot_devices",
  {
    id: idCol(),
    deviceId: text("device_id").notNull().unique(), // stable hardware identifier printed on the robot
    displayName: text("display_name").notNull(),
    locationId: text("location_id").references(() => campusLocations.id, { onDelete: "set null" }),
    status: text("status").$type<(typeof DEVICE_STATUSES)[number]>().notNull().default("OFFLINE"),
    mode: text("mode").$type<(typeof DEVICE_MODES)[number]>().notNull().default("ASSISTANT"),
    firmwareVersion: text("firmware_version"),
    batteryPercent: integer("battery_percent"),
    currentDestinationId: text("current_destination_id").references(() => navigationDestinations.id, { onDelete: "set null" }),
    /** true while the device only exists as a simulator — never mixed with real telemetry. */
    simulated: boolean("simulated").notNull().default(true),
    active: boolean("active").notNull().default(true),
    /**
     * Bearer token held by the tablet paired with this robot (generated by an administrator,
     * shown once, revocable by rotating it). It scopes NFC identification events to that
     * terminal without exposing device secrets to a public tablet.
     */
    terminalToken: text("terminal_token").unique(),
    lastSeenAt: timestamp("last_seen_at", { withTimezone: true }),
    // Safe operating limits configured by an administrator.
    maxSpeedPercent: integer("max_speed_percent").notNull().default(60),
    safetyTimeoutSeconds: integer("safety_timeout_seconds").notNull().default(10),
    createdAt: createdAtCol(),
    updatedAt: updatedAtCol(),
  },
  (t) => [
    index("robot_devices_status_idx").on(t.status),
    index("robot_devices_active_idx").on(t.active),
  ],
);

/** Device secrets, isolated from public device metadata. Plaintext is shown exactly once at registration. */
export const deviceCredentials = pgTable(
  "device_credentials",
  {
    id: idCol(),
    deviceId: text("device_id")
      .notNull()
      .references(() => robotDevices.deviceId, { onDelete: "cascade" }),
    /** AES-256-GCM ciphertext keyed by DEVICE_AUTH_SECRET — verified, never returned. */
    secretEncrypted: text("secret_encrypted").notNull(),
    /** Non-reversible fingerprint for rotation/support bookkeeping. */
    secretFingerprint: text("secret_fingerprint").notNull(),
    revokedAt: timestamp("revoked_at", { withTimezone: true }),
    rotatedAt: timestamp("rotated_at", { withTimezone: true }),
    createdAt: createdAtCol(),
  },
  (t) => [uniqueIndex("device_credentials_device_unique").on(t.deviceId)],
);

/** Device telemetry samples and events. `simulated` marks simulator traffic explicitly. */
export const robotTelemetry = pgTable(
  "robot_telemetry",
  {
    id: idCol(),
    deviceId: text("device_id")
      .notNull()
      .references(() => robotDevices.deviceId, { onDelete: "cascade" }),
    batteryPercent: integer("battery_percent"),
    speedPercent: integer("speed_percent"),
    obstacleDistanceCm: integer("obstacle_distance_cm"),
    mode: text("mode").$type<(typeof DEVICE_MODES)[number]>(),
    simulated: boolean("simulated").notNull().default(false),
    recordedAt: timestamp("recorded_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [index("robot_telemetry_device_time_idx").on(t.deviceId, t.recordedAt)],
);

export const deviceEvents = pgTable(
  "device_events",
  {
    id: idCol(),
    deviceId: text("device_id")
      .notNull()
      .references(() => robotDevices.deviceId, { onDelete: "cascade" }),
    type: text("type").notNull(), // NFC_SCAN_STARTED | STUDENT_IDENTIFIED | ...
    payload: jsonb("payload").$type<Record<string, unknown>>().notNull().default({}),
    /** Supplied by producers so repeated NFC reads of the same card are stored once. */
    dedupeKey: text("dedupe_key"),
    simulated: boolean("simulated").notNull().default(false),
    createdAt: createdAtCol(),
  },
  (t) => [
    index("device_events_device_time_idx").on(t.deviceId, t.createdAt),
    index("device_events_type_idx").on(t.type),
    uniqueIndex("device_events_dedupe_unique").on(t.deviceId, t.dedupeKey),
  ],
);

/**
 * Remote robot commands. Never issued directly by the AI model: a validated service
 * creates the row, the device acknowledges it, and the backend only reports a state
 * the device actually confirmed.
 */
export const robotCommands = pgTable(
  "robot_commands",
  {
    id: idCol(),
    deviceId: text("device_id")
      .notNull()
      .references(() => robotDevices.deviceId, { onDelete: "cascade" }),
    type: text("type").$type<(typeof COMMAND_TYPES)[number]>().notNull(),
    payload: jsonb("payload").$type<Record<string, unknown>>().notNull().default({}),
    status: text("status").$type<(typeof COMMAND_STATUSES)[number]>().notNull().default("PENDING"),
    /** STOP is always treated as high priority and bypasses the queue. */
    priority: text("priority").notNull().default("NORMAL"), // NORMAL | EMERGENCY
    issuedByUserId: text("issued_by_user_id").references(() => users.id, { onDelete: "set null" }),
    issuedByService: text("issued_by_service"),
    confirmationToken: text("confirmation_token"),
    failureReason: text("failure_reason"),
    dedupeKey: text("dedupe_key"),
    createdAt: createdAtCol(),
    expiresAt: timestamp("expires_at", { withTimezone: true }).notNull(),
    ackedAt: timestamp("acked_at", { withTimezone: true }),
    completedAt: timestamp("completed_at", { withTimezone: true }),
    updatedAt: updatedAtCol(),
  },
  (t) => [
    index("robot_commands_device_status_idx").on(t.deviceId, t.status),
    index("robot_commands_status_created_idx").on(t.status, t.createdAt),
    index("robot_commands_expiry_idx").on(t.expiresAt),
    uniqueIndex("robot_commands_dedupe_unique").on(t.deviceId, t.dedupeKey),
  ],
);
